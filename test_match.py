conn = sqlite3.connect(DB_PATH)
rows = conn.execute("SELECT id, question, solution FROM problems WHERE solution IS NOT NULL AND solution != ''").fetchall()
conn.close()

matched, unmatched = [], []
concept_dist = Counter()

for pid, question, solution in rows:
    counts = Counter()
    for concept, keywords in ECON_CONCEPTS.items():
        for kw in keywords:
            counts[concept] += solution.count(kw)
    hits = sorted([(c, n) for c, n in counts.items() if n > 0], key=lambda x: -x[1])
    if hits:
        matched.append((pid, question, hits[0][0]))
        concept_dist[hits[0][0]] += 1
    else:
        unmatched.append((pid, question, solution[:100]))

print(f"전체: {len(rows)}개")
print(f"매칭 성공: {len(matched)}개 ({round(len(matched)/len(rows)*100)}%)")
print(f"매칭 실패: {len(unmatched)}개")
print()
print("=== 개념별 분포 ===")
for concept, cnt in concept_dist.most_common():
    print(f"  {concept}: {cnt}개")
print()
